import { expect, test } from '@playwright/test';
import { storyModeFixture } from './story-mode-fixture';
import { finishReading, speechState } from './speech-mock';

test('story mode follows event locations while preserving speech and navigation', async ({ page }, testInfo) => {
  const errors: string[] = [];
  page.on('pageerror', (error) => errors.push(error.message));
  const project = await storyModeFixture(page);
  await page.getByRole('button', { name: 'Play story', exact: true }).click();
  await expect.poll(async () => (await speechState(page)).texts.length).toBe(1);
  await page.getByRole('button', { name: 'Story mode', exact: true }).click();
  const mode = page.getByRole('main', { name: 'Story mode', exact: true });
  await expect(mode).toBeVisible();
  await expect(mode.getByRole('heading', { level: 1 })).toHaveText(project.events[0].title);
  await expect(mode.locator('.story-location')).toContainText('Synthetic western city');
  await mode.getByText('Map sources', { exact: true }).click();
  await expect(mode.locator('.story-map-sources a')).toHaveAttribute('href', 'https://example.org/synthetic');
  await expect(mode.locator('.story-map-sources')).toContainText('Synthetic test gazetteer');
  await mode.getByText('Map sources', { exact: true }).click();
  await expect(mode.locator('.leaflet-interactive')).toHaveCount(1);
  await expect.poll(async () => {
    const marker = await mode.locator('.leaflet-interactive').boundingBox();
    const reading = await mode.locator('.story-reading').boundingBox();
    return !!marker && !!reading && marker.x > 0 && marker.x + marker.width < reading.x;
  }).toBe(true);
  await mode.screenshot({ path: testInfo.outputPath('story-mode.png') });
  expect((await speechState(page)).texts).toHaveLength(1);
  await mode.getByRole('button', { name: 'Pause story', exact: true }).click();
  await expect.poll(async () => (await speechState(page)).pauses).toBe(1);
  await mode.getByRole('button', { name: 'Play story', exact: true }).click();
  await expect.poll(async () => (await speechState(page)).resumes).toBe(1);
  await finishReading(page);
  await expect(mode.locator('.story-location')).toContainText('Synthetic eastern city');
  await expect(mode.getByRole('heading', { level: 1 })).toHaveText(project.events[1].title);
  await mode.getByRole('button', { name: 'Follow location', exact: true }).click();
  await expect(mode.getByRole('button', { name: 'Follow location', exact: true })).toHaveAttribute('aria-pressed', 'false');
  await mode.getByRole('button', { name: 'Next milestone', exact: true }).click();
  await expect(mode.getByRole('heading', { level: 1 })).toHaveText(project.events[2].title);
  await mode.getByRole('button', { name: 'Follow location', exact: true }).click();
  await mode.getByLabel('Story chapter', { exact: true }).selectOption('last');
  await expect(mode.locator('.story-location')).toContainText('Synthetic western city / Synthetic eastern city');
  await expect(mode.locator('.leaflet-interactive')).toHaveCount(2);
  await mode.getByRole('button', { name: 'Next milestone', exact: true }).click();
  await expect(mode.locator('.story-location')).toContainText('No location recorded');
  await expect(mode.getByRole('heading', { level: 1 })).toHaveText(project.events[4].title);
  await page.setViewportSize({ width: 720, height: 1024 });
  await expect(mode.locator('.story-location')).toBeVisible();
  await mode.screenshot({ path: testInfo.outputPath('story-mode-narrow.png') });
  await finishReading(page);
  await expect(mode.locator('.story-progress')).toContainText('Story complete');
  await mode.getByRole('button', { name: 'Restart story', exact: true }).click();
  await expect(mode.getByRole('heading', { level: 1 })).toHaveText(project.events[0].title);
  const count = (await speechState(page)).texts.length;
  await mode.getByRole('button', { name: 'Restart story', exact: true }).click();
  await expect.poll(async () => (await speechState(page)).texts.length).toBe(count + 1);
  await mode.getByRole('button', { name: 'Exit story mode', exact: true }).click();
  await expect(mode).toHaveCount(0);
  await expect(page.locator('.event-story')).toContainText('Supporting evidence has not yet been verified');
  expect(errors).toEqual([]);
});

test('story fullscreen keeps voice settings available and returns to the map view', async ({ page }) => {
  await storyModeFixture(page);
  await page.getByRole('button', { name: 'Show map view', exact: true }).click();
  await page.getByRole('button', { name: 'Story', exact: true }).click();
  const mode = page.getByRole('main', { name: 'Story mode', exact: true });
  await mode.getByRole('button', { name: 'Toggle story fullscreen', exact: true }).click();
  await expect.poll(() => page.evaluate(() => document.fullscreenElement?.className)).toBe('story-mode');
  await mode.getByRole('button', { name: 'Voice & playback', exact: true }).click();
  await expect(page.getByRole('dialog', { name: 'Voice & playback', exact: true })).toBeVisible();
  await page.getByLabel('Voice', { exact: true }).selectOption('test-b');
  await page.getByLabel('Close dialog').click();
  await page.evaluate(() => document.exitFullscreen());
  await page.keyboard.press('Escape');
  await expect(mode).toHaveCount(0);
  await expect(page.getByLabel('Historical places map', { exact: true })).toBeVisible();
});
